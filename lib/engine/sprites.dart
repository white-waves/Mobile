List<String> _rotate(List<String> rows) {
  final h = rows.length;
  final w = rows.first.length;
  return [
    for (var x = 0; x < w; x++) [for (var y = h - 1; y >= 0; y--) rows[y][x]].join(),
  ];
}

// Затоплений корабель: лишається кожен другий піксель.
List<String> _wreck(List<String> rows) => [
      for (var y = 0; y < rows.length; y++)
        [
          for (var x = 0; x < rows[y].length; x++)
            rows[y][x] == '.' ? '.' : ((x + y).isEven ? '#' : '+'),
        ].join(),
    ];

ui.Image _image(List<String> rows, {int? width, int? height}) {
  final w = width ?? rows.first.length;
  final h = height ?? rows.length;
  final recorder = ui.PictureRecorder();
  final canvas = ui.Canvas(recorder);
  for (var y = 0; y < rows.length; y++) {
    for (var x = 0; x < rows[y].length; x++) {
      final c = rows[y][x];
      if (c == '#') canvas.px(x.toDouble(), y.toDouble());
      if (c == '+') canvas.px(x.toDouble(), y.toDouble(), 1, 1, true);
    }
  }
  return recorder.endRecording().toImageSync(w, h);
}

enum Segment { stern, mid, bow, boat }

class Sprites {
  static late Map<(Segment, bool vertical, bool sunk), ui.Image> _segments;
  static late List<ui.Image> water;
  static late ui.Image calmWater;
  static late ui.Image debris;
  static late ui.Image holesH;
  static late ui.Image holesV;
  static late List<ui.Image> fire;
  static late ui.Image buoy;
  static late List<ui.Image> cross;
  static bool _built = false;
  static bool? _builtFor;

  static ui.Image segment(Segment s, {bool vertical = false, bool sunk = false}) =>
      _segments[(s, vertical, sunk)]!;

  // Перебудова при зміні палітри (інверсії).
  static void build() {
    if (_built && _builtFor == Palette.inverted) return;
    final art = {
      Segment.stern: _stern,
      Segment.mid: _mid,
      Segment.bow: _bow,
      Segment.boat: _boat,
    };
    _segments = {};
    for (final entry in art.entries) {
      for (final vertical in [false, true]) {
        for (final sunk in [false, true]) {
          var rows = entry.value;
          if (sunk) rows = _wreck(rows);
          if (vertical) rows = _rotate(rows);
          _segments[(entry.key, vertical, sunk)] = _image(rows);
        }
      }
    }
    water = [for (var f = 0; f < 8; f++) _waterFrame(f)];
    calmWater = _waterFrame(-1);
    debris = _image(_debris);
    holesH = _image(_holes);
    holesV = _image(_rotate(_holes));
    fire = [for (final f in _fire) _image(f, width: tile, height: tile)];
    buoy = _image(_buoy);
    cross = [for (final c in _cross) _image(c)];
    _built = true;
    _builtFor = Palette.inverted;
  }

  // Клітинка води: пунктир сітки по верхньому й лівому краю та хвилька,
  // що зсувається на 2 пікселі за кадр (8 кадрів - повний цикл).
  // frame = -1 - спокійна вода без хвильки.
  static ui.Image _waterFrame(int frame) {
    final rows = List.generate(tile, (_) => List.filled(tile, '+'));
    for (var i = 0; i < tile; i += 2) {
      rows[0][i] = '#';
      rows[i][0] = '#';
    }
    void wave(int x0, int y) {
      for (final (dx, dy) in [(0, 1), (1, 0), (2, 0), (3, 1)]) {
        final x = (x0 + dx) % tile;
        if (x == 0) continue;
        rows[y + dy][x] = '#';
      }
    }

    if (frame >= 0) wave(5 + frame * 2, 8);
    return _image([for (final r in rows) r.join()]);
  }
}
